#!/bin/bash
# Builds and signs build/streamplus.apk with plain SDK tools (no Gradle, no libraries),
# the same toolchain as Hume Launcher+.
#   ./build.sh            build only
#   ./build.sh install    build + install + grant overlay permission on $TV (ip:port)
set -euo pipefail
cd "$(dirname "$0")"

# d8 (build-tools 34) needs class files from JDK 17.
if [ -z "${JAVA_HOME:-}" ]; then
    for j in /opt/homebrew/opt/openjdk@17 "$HOME/.local/jdk-17.0.20.1+1/Contents/Home"; do [ -d "$j" ] && JAVA_HOME="$j" && break; done
fi
if [ -n "${JAVA_HOME:-}" ]; then export JAVA_HOME; export PATH="$JAVA_HOME/bin:$PATH"; fi
SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-$HOME/Library/Android/sdk}}"
BT="$SDK/build-tools/34.0.0"
JAR="$SDK/platforms/android-34/android.jar"
for f in "$BT/aapt2" "$BT/d8" "$JAR"; do
    [ -e "$f" ] || { echo "Missing $f — install build-tools 34.0.0 and platform android-34." >&2; exit 1; }
done

# Android package id. A personal build can set its own in personal/build.env (PACKAGE=…, APK=…).
PACKAGE=com.hugo.streamplus
APK=streamplus.apk
[ -f personal/build.env ] && . personal/build.env
MANIFEST=AndroidManifest.xml
[ -f personal/AndroidManifest.xml ] && MANIFEST=personal/AndroidManifest.xml
RENAME=()
[ "$PACKAGE" != com.hugo.streamplus ] && RENAME=(--rename-manifest-package "$PACKAGE")

rm -rf build && mkdir -p build/gen build/classes build/dex build/assets
cp -R assets/. build/assets/
# Optional personal config (Twitch Client ID…), never committed.
if [ -f config.json ]; then cp config.json build/assets/web/config.json; else echo '{}' > build/assets/web/config.json; fi

# Personal art (personal/, never committed): replaces the app's logos when present.
mkdir -p build/res && cp -R res/. build/res/
[ -d personal/res ] && cp -R personal/res/. build/res/
[ -f build/assets/web/personal.css ] || : > build/assets/web/personal.css
[ -d personal/web ] && cp -R personal/web/. build/assets/web/

# Plugins: folders or .zip files in plugins/ (and personal/plugins/), see plugins/README.md.
mkdir -p build/plugins
: > build/assets/web/plugins.js
: > build/assets/web/player-plugins.js
: > build/plugins.manifest.xml
PLUGIN_CLASSES=""
for p in plugins/* personal/plugins/*; do
    [ -e "$p" ] || continue
    n=$(basename "$p"); n="${n%.zip}"; d="build/plugins/$n"
    if [ -d "$p" ]; then mkdir -p "$d" && cp -R "$p/." "$d/"
    elif [[ "$p" == *.zip ]]; then mkdir -p "$d" && unzip -q -o "$p" -d "$d"
    else continue; fi
    [ -f "$d/plugin.properties" ] || { echo "Plugin $n ignored: no plugin.properties" >&2; rm -rf "$d"; continue; }
    c=$(sed -n 's/^class=//p' "$d/plugin.properties" | tr -d '\r')
    [ -n "$c" ] && PLUGIN_CLASSES="$PLUGIN_CLASSES \"$c\","
    for j in "$d"/web/*.js; do [ -f "$j" ] && { cat "$j"; echo; } >> build/assets/web/plugins.js; done
    for j in "$d"/player/*.js; do [ -f "$j" ] && { cat "$j"; echo; } >> build/assets/web/player-plugins.js; done
    for f in "$d"/web/*; do [ -f "$f" ] && [[ "$f" != *.js ]] && cp "$f" build/assets/web/; done
    [ -f "$d/manifest.xml" ] && cat "$d/manifest.xml" >> build/plugins.manifest.xml
    echo "Plugin: $n"
done
awk -v f=build/plugins.manifest.xml '/<\/application>/ { while ((getline l < f) > 0) print l } { print }' "$MANIFEST" > build/AndroidManifest.xml

"$BT/aapt2" compile --dir build/res -o build/res.zip
"$BT/aapt2" link -o build/unsigned.apk -I "$JAR" --manifest build/AndroidManifest.xml \
    -A build/assets --java build/gen --min-sdk-version 26 --target-sdk-version 34 \
    --version-code "${VERSION_CODE:-1}" --version-name "${VERSION_NAME:-1.0}" ${RENAME[@]+"${RENAME[@]}"} build/res.zip

mkdir -p build/gen/com/hugo/streamplus
printf 'package com.hugo.streamplus;\n/** Generated by build.sh: the plugins found in plugins/. */\nfinal class Plugins {\n    static final String[] CLASSES = {%s };\n}\n' "$PLUGIN_CLASSES" > build/gen/com/hugo/streamplus/Plugins.java

javac -encoding UTF-8 --release 11 -nowarn -Xlint:-options -classpath "$JAR" \
    -d build/classes $(find src build/gen build/plugins -name '*.java')
"$BT/d8" --release --min-api 26 --lib "$JAR" --output build/dex $(find build/classes -name '*.class')
(cd build/dex && zip -q ../unsigned.apk classes.dex)
"$BT/zipalign" -f 4 build/unsigned.apk build/aligned.apk

KS=debug.keystore
if [ ! -f "$KS" ]; then
    keytool -genkeypair -keystore "$KS" -storepass android -keypass android -alias debug \
        -keyalg RSA -keysize 2048 -validity 10000 -dname "CN=StreamPlus debug" >/dev/null 2>&1
fi
"$BT/apksigner" sign --ks "$KS" --ks-pass pass:android --key-pass pass:android \
    --out "build/$APK" build/aligned.apk
echo "Built build/$APK"

if [ "${1:-}" = "install" ]; then
    TV="${TV:?set TV=ip:port of your Google TV, e.g. TV=192.168.1.20:5555 ./build.sh install}"
    adb connect "$TV" >/dev/null || true
    adb -s "$TV" install -r "build/$APK"
    # Floating player (PiP) over other apps: Google TV hides this setting, so grant it here.
    adb -s "$TV" shell appops set "$PACKAGE" SYSTEM_ALERT_WINDOW allow
    adb -s "$TV" shell am start -n "$PACKAGE/com.hugo.streamplus.MainActivity"
fi
