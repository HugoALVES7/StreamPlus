package com.hugo.streamplus;

import android.app.Activity;
import android.content.Intent;
import android.os.Bundle;
import android.view.KeyEvent;
import android.view.View;
import android.webkit.WebChromeClient;
import android.webkit.WebView;

import org.json.JSONObject;

/** Full-screen host of the web UI (assets/web). */
public class MainActivity extends Activity {
    WebView web;
    private final java.util.List<Plugin> plugins = new java.util.ArrayList<>();
    private boolean loaded;
    private String pendingOpen;

    @Override protected void onCreate(Bundle b) {
        super.onCreate(b);
        // Inspectable over adb (chrome://inspect) for debugging on the TV.
        WebView.setWebContentsDebuggingEnabled(true);
        web = new WebView(this);
        Web.setup(web);
        web.setWebChromeClient(new WebChromeClient() {
            @Override public boolean onConsoleMessage(android.webkit.ConsoleMessage m) {
                android.util.Log.d("StreamPlus", m.message() + " @" + m.lineNumber());
                return true;
            }
        });
        web.addJavascriptInterface(new Bridge(this, web), "Native");
        // Plugins found in plugins/ at build time (Plugins.CLASSES is generated by build.sh).
        for (String c : Plugins.CLASSES) {
            try {
                Plugin p = (Plugin) Class.forName(c).getDeclaredConstructor().newInstance();
                p.attach(this, web);
                plugins.add(p);
            } catch (Throwable t) {
                android.util.Log.w("StreamPlus", "plugin " + c, t);
            }
        }
        web.setWebViewClient(new android.webkit.WebViewClient() {
            @Override public android.webkit.WebResourceResponse shouldInterceptRequest(WebView v, android.webkit.WebResourceRequest r) {
                return Web.intercept(v.getContext(), r);
            }

            @Override public boolean shouldOverrideUrlLoading(WebView v, android.webkit.WebResourceRequest r) {
                return r.isForMainFrame() && !Web.HOST.equals(r.getUrl().getHost());
            }

            @Override public void onPageFinished(WebView v, String url) {
                loaded = true;
                if (pendingOpen != null) {
                    js("app.openExternal(" + pendingOpen + ")");
                    pendingOpen = null;
                }
            }
        });
        // Full-screen host of the WebView.
        android.widget.FrameLayout root = new android.widget.FrameLayout(this);
        root.addView(web, new android.widget.FrameLayout.LayoutParams(-1, -1));
        setContentView(root);
        web.setSystemUiVisibility(View.SYSTEM_UI_FLAG_FULLSCREEN | View.SYSTEM_UI_FLAG_HIDE_NAVIGATION
                | View.SYSTEM_UI_FLAG_IMMERSIVE_STICKY | View.SYSTEM_UI_FLAG_LAYOUT_STABLE);
        if (b != null) web.restoreState(b);
        else web.loadUrl(Web.ORIGIN + "/index.html");
        handleIntent(getIntent());
        web.requestFocus();
    }

    @Override protected void onSaveInstanceState(Bundle out) {
        super.onSaveInstanceState(out);
        web.saveState(out);
    }

    @Override protected void onNewIntent(Intent i) {
        super.onNewIntent(i);
        handleIntent(i);
    }

    /** "Plein écran" from the PiP panel: reopen the stream here. */
    private void handleIntent(Intent i) {
        if (i == null || !i.hasExtra("open")) return;
        String json = JSONObject.quote(i.getStringExtra("open"));
        i.removeExtra("open");
        if (loaded) js("app.openExternal(" + json + ")");
        else pendingOpen = json;
    }

    void js(String s) {
        web.evaluateJavascript("window.app && " + s, null);
    }

    @Override public void onBackPressed() {
        web.evaluateJavascript("window.app ? app.back() : false", v -> {
            if (!"true".equals(v)) finish();
        });
    }

    /** True while a card (something with a long-press menu) has the focus in the web UI. */
    volatile boolean okMode;
    private boolean okDown, okLong;
    private final android.os.Handler ui = new android.os.Handler(android.os.Looper.getMainLooper());
    private final Runnable okTimer = () -> { okLong = true; js("app.ok(true)"); };

    @Override public boolean dispatchKeyEvent(KeyEvent e) {
        int k = e.getKeyCode();
        // Long press OK on a card: measured here, before the WebView, whatever the remote sends
        // while the key is held (repeats or not).
        boolean okKey = k == KeyEvent.KEYCODE_DPAD_CENTER || k == KeyEvent.KEYCODE_ENTER || k == KeyEvent.KEYCODE_NUMPAD_ENTER;
        // The release belongs to the press we took, even if the menu has moved the focus meanwhile
        // (otherwise it would validate the menu's first button).
        if (okKey && okDown) {
            if (e.getAction() == KeyEvent.ACTION_UP) {
                okDown = false;
                ui.removeCallbacks(okTimer);
                if (!okLong) js("app.ok(false)");
            }
            return true;
        }
        if (okMode && okKey) {
            if (e.getAction() == KeyEvent.ACTION_DOWN) {
                if (!okDown) { okDown = true; okLong = false; ui.postDelayed(okTimer, 450); }
                return true;
            }
            if (e.getAction() == KeyEvent.ACTION_UP) {
                if (okDown) {
                    okDown = false;
                    ui.removeCallbacks(okTimer);
                    if (!okLong) js("app.ok(false)");
                }
                return true;
            }
        }
        String name = null;
        switch (k) {
            case KeyEvent.KEYCODE_MENU: name = "menu"; break;
            case KeyEvent.KEYCODE_MEDIA_PLAY_PAUSE:
            case KeyEvent.KEYCODE_MEDIA_PLAY:
            case KeyEvent.KEYCODE_MEDIA_PAUSE: name = "playpause"; break;
            case KeyEvent.KEYCODE_MEDIA_FAST_FORWARD: name = "ff"; break;
            case KeyEvent.KEYCODE_MEDIA_REWIND: name = "rew"; break;
            case KeyEvent.KEYCODE_CHANNEL_UP: name = "chup"; break;
            case KeyEvent.KEYCODE_CHANNEL_DOWN: name = "chdown"; break;
            case KeyEvent.KEYCODE_INFO:
            case KeyEvent.KEYCODE_GUIDE: name = "info"; break;
            default: break;
        }
        if (name != null) {
            if (e.getAction() == KeyEvent.ACTION_DOWN) js("app.key('" + name + "')");
            return true;
        }
        return super.dispatchKeyEvent(e);
    }

    /** Home pressed while a single stream plays: it continues in the floating player. */
    @Override protected void onUserLeaveHint() {
        super.onUserLeaveHint();
        js("app.autoPip()");
    }

    @Override protected void onResume() {
        super.onResume();
        web.onResume();
        js("app.onResume()");
    }

    @Override protected void onStop() {
        super.onStop();
        js("app.onStop()");
    }

    @Override protected void onDestroy() {
        for (Plugin p : plugins) try { p.detach(); } catch (Throwable ignored) { }
        web.destroy();
        super.onDestroy();
    }
}
